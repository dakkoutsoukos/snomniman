"""Generate the Windows version-info resource (``packaging/version_info.txt``)
consumed by PyInstaller's ``EXE(version=...)``.

Reads the version string from ``pyproject.toml`` so the frozen exe's
Properties > Details tab, the running app's provenance-recorded software
version, and the packaging version are one identity, never three
separately-maintained numbers (deployment-strategy.md Section 6). Rerun
manually whenever ``pyproject.toml``'s version changes, then rebuild.
"""

from __future__ import annotations

import tomllib
from pathlib import Path

REPO_ROOT = Path(__file__).parent.parent


def main() -> None:
    pyproject = tomllib.loads((REPO_ROOT / "pyproject.toml").read_text(encoding="utf-8"))
    version = pyproject["project"]["version"]
    parts = [int(p) for p in version.split(".")]
    while len(parts) < 4:
        parts.append(0)
    filevers = tuple(parts[:4])

    content = f"""# UTF-8
#
# Generated by packaging/make_version_info.py from pyproject.toml's version
# ({version}). Do not hand-edit the version numbers - rerun the script.
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={filevers!r},
    prodvers={filevers!r},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0),
  ),
  kids=[
    StringFileInfo(
      [
        StringTable(
          u"040904B0",
          [
            StringStruct(u"CompanyName", u"SNOMNIMAN Project"),
            StringStruct(u"FileDescription", u"SNOMNIMAN Measurement Explorer"),
            StringStruct(u"FileVersion", u"{version}"),
            StringStruct(u"InternalName", u"SNOMNIMAN"),
            StringStruct(u"LegalCopyright", u"SNOMNIMAN is open research software."),
            StringStruct(u"OriginalFilename", u"SNOMNIMAN.exe"),
            StringStruct(u"ProductName", u"SNOMNIMAN"),
            StringStruct(u"ProductVersion", u"{version}"),
          ],
        )
      ]
    ),
    VarFileInfo([VarStruct(u"Translation", [1033, 1200])]),
  ],
)
"""
    out = REPO_ROOT / "packaging" / "version_info.txt"
    out.write_text(content, encoding="utf-8")
    print(f"wrote {out} (version {version})")


if __name__ == "__main__":
    main()
